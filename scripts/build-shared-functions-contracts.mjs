import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';

const output = 'functions/lib/generated/sharedDailyRecordContracts.cjs';
const check = process.argv.includes('--check');

const result = await build({
  entryPoints: ['src/services/sharedFunctionsContractsServerEntry.ts'],
  outfile: output,
  write: !check,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  banner: {
    js: '// @ts-nocheck\n// Generated by scripts/build-shared-functions-contracts.mjs. Do not edit.',
  },
});

if (check) {
  let current = '';
  try {
    current = await readFile(output, 'utf8');
  } catch {
    throw new Error(
      `Shared daily-record contracts bundle is missing (${output}). Run node scripts/build-shared-functions-contracts.mjs.`
    );
  }
  if (current !== result.outputFiles[0].text) {
    throw new Error(
      'Shared daily-record contracts bundle is stale. Run node scripts/build-shared-functions-contracts.mjs.'
    );
  }
}
