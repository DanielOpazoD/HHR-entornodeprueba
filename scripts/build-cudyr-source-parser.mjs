import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
const output = 'functions/lib/generated/cudyrSourceParser.cjs';
const check = process.argv.includes('--check');
const result = await build({
  entryPoints: ['src/services/cudyr/cudyrSourceServerEntry.ts'],
  outfile: output,
  write: !check,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  external: ['xlsx'],
  banner: { js: '// Generated by scripts/build-cudyr-source-parser.mjs. Do not edit.' },
});

if (check && (await readFile(output, 'utf8')) !== result.outputFiles[0].text) {
  throw new Error('CUDYR source parser is stale. Run node scripts/build-cudyr-source-parser.mjs.');
}
