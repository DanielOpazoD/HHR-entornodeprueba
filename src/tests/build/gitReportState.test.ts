// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { hasMeaningfulWorktreeChanges } from '../../../scripts/gitReportState.mjs';

describe('gitReportState', () => {
  it('ignores release evidence reports regenerated by the release pipeline', () => {
    expect(
      hasMeaningfulWorktreeChanges(
        [
          ' M reports/quality-metrics.json',
          ' M reports/system-confidence.md',
          ' M reports/operational-health.json',
          ' M reports/clinical-release-validation.md',
          ' M reports/clinical-release-signoff.json',
          ' M reports/clinical-release-signoff.md',
          ' M reports/release-confidence-matrix.json',
          ' M reports/release-readiness-scorecard.md',
          ' M reports/maintenance-debt-scorecard.json',
          ' M reports/bundle-risk-ledger.json',
          ' M reports/bundle-risk-ledger.md',
          ' M reports/sync-convergence.json',
          ' M reports/sync-convergence.md',
        ].join('\n')
      )
    ).toBe(false);
  });

  it('keeps non-generated paths as meaningful worktree changes', () => {
    expect(hasMeaningfulWorktreeChanges(' M src/app.ts\n')).toBe(true);
  });
});
